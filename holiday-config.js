// 根據年份取得假日清單
function getHolidaysByYear(year) {
  switch(year) {
    case 2025:
      return holidays2025;
    case 2026:
      return holidays2026;
    default:
      console.warn(`Warning: No holiday data for year ${year}, returning empty object`);
      return {};
  }
}

// 檢查指定日期是否為假日
function isHoliday(dateStr) {
  const year = parseInt(dateStr.substring(0, 4));
  const holidays = getHolidaysByYear(year);
  return holidays[dateStr] || null;
}

